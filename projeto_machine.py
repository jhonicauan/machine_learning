import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler, OrdinalEncoder
from sklearn.linear_model import LinearRegression
from sklearn.neighbors import KNeighborsRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

random_seed = 42

"""## 2. Carregamento dos dados"""

df = pd.read_csv('house_price_50k.csv')
print('Formato (linhas, colunas):', df.shape)
df.head()

"""## 3. Análise Exploratória de Dados (EDA)"""

df.info()

df.describe()

print('Valores ausentes por coluna:')
print(df.isnull().sum())

"""## 3.1. Diagnóstico de Outliers"""

colunas_num = df.select_dtypes(include=[np.number]).columns

diag_outliers = []

for c in colunas_num:
    q1 = df[c].quantile(0.25)
    q3 = df[c].quantile(0.75)
    iqr = q3 - q1
    limite_inferior = q1 - 1.5 * iqr
    limite_superior = q3 + 1.5 * iqr

    n_outliers = 0
    for valor in df[c]:
        if valor < limite_inferior or valor > limite_superior:
            n_outliers = n_outliers + 1

    diag_outliers.append({
        'campo': c,
        'limite_inferior': round(limite_inferior, 2),
        'limite_superior': round(limite_superior, 2),
        'n_outliers': n_outliers,
    })

tabela_outliers = pd.DataFrame(diag_outliers)
tabela_outliers

"""## 3.2. Contagem de Classes e Verificação de Desbalanceamento"""

def analisar_balanceamento(coluna):
    contagem = df[coluna].value_counts()
    porcentagem = (contagem / len(df) * 100).round(2)
    tabela = pd.DataFrame({'contagem': contagem, 'porcentagem(%)': porcentagem})
    return tabela

analisar_balanceamento('location')

analisar_balanceamento('income_level')

fig, eixos = plt.subplots(1, 2, figsize=(11, 4))

df['location'].value_counts().plot(kind='bar', ax=eixos[0], color='teal', edgecolor='black')
eixos[0].set_title('Distribuição de location (contagem)')
eixos[0].set_ylabel('Contagem')
eixos[0].tick_params(axis='x', rotation=0)

pct_location = df['location'].value_counts(normalize=True) * 100
pct_location.plot(kind='bar', ax=eixos[1], color='teal', edgecolor='black')
eixos[1].set_title('Distribuição de location (%)')
eixos[1].set_ylabel('Porcentagem (%)')
eixos[1].tick_params(axis='x', rotation=0)
for i, v in enumerate(pct_location):
    eixos[1].text(i, v + 0.3, f'{v:.2f}%', ha='center', fontsize=9)

plt.tight_layout()
plt.show()

fig, eixos = plt.subplots(1, 2, figsize=(11, 4))

df['income_level'].value_counts().plot(kind='bar', ax=eixos[0], color='darkorange', edgecolor='black')
eixos[0].set_title('Distribuição de income_level (contagem)')
eixos[0].set_ylabel('Contagem')
eixos[0].tick_params(axis='x', rotation=0)

pct_income_level = df['income_level'].value_counts(normalize=True) * 100
pct_income_level.plot(kind='bar', ax=eixos[1], color='darkorange', edgecolor='black')
eixos[1].set_title('Distribuição de income_level (%)')
eixos[1].set_ylabel('Porcentagem (%)')
eixos[1].tick_params(axis='x', rotation=0)
for i, v in enumerate(pct_income_level):
    eixos[1].text(i, v + 0.3, f'{v:.2f}%', ha='center', fontsize=9)

plt.tight_layout()
plt.show()

"""## 3.3. Histograma da variável alvo"""

plt.figure(figsize=(8, 4))
plt.hist(df['price'], bins=50, edgecolor='black')
plt.title('Distribuição do preço dos imóveis')
plt.xlabel('Preço')
plt.ylabel('Frequência')
plt.show()

"""## 4. Pré-processamento e Feature Engineering"""

X = df.drop(columns=['price']).copy()
y = df['price']

ordem_location = ['low', 'medium', 'premium']
ordem_income = ['low', 'mid', 'high']

codificador = OrdinalEncoder(categories=[ordem_location, ordem_income])
X[['location', 'income_level']] = codificador.fit_transform(X[['location', 'income_level']])

X.head()

X_treino, X_teste, y_treino, y_teste = train_test_split(
    X, y, test_size=0.2, random_state=random_seed
)

print('Tamanho do treino:', X_treino.shape)
print('Tamanho do teste :', X_teste.shape)

escalonador = StandardScaler()
X_treino_esc = escalonador.fit_transform(X_treino)
X_teste_esc = escalonador.transform(X_teste)

"""## 5. Modelo A — Regressão Linear Múltipla"""

modelo_linear = LinearRegression()
modelo_linear.fit(X_treino_esc, y_treino)
y_pred_linear = modelo_linear.predict(X_teste_esc)

mae_linear = mean_absolute_error(y_teste, y_pred_linear)
mse_linear = mean_squared_error(y_teste, y_pred_linear)
rmse_linear = np.sqrt(mse_linear)
r2_linear = r2_score(y_teste, y_pred_linear)

print(f'MAE : {mae_linear:,.2f}')
print(f'MSE : {mse_linear:,.2f}')
print(f'RMSE: {rmse_linear:,.2f}')
print(f'R²  : {r2_linear:.4f}')

importancia_linear = pd.DataFrame({
    'variavel': X.columns,
    'coeficiente': modelo_linear.coef_
}).sort_values(by='coeficiente', key=abs, ascending=True)

cores = ['crimson' if v < 0 else 'seagreen' for v in importancia_linear['coeficiente']]

plt.figure(figsize=(9, 6))
plt.barh(importancia_linear['variavel'], importancia_linear['coeficiente'],
         color=cores, edgecolor='black')
plt.axvline(0, color='black', linewidth=0.7)
plt.title('Importância das variáveis — Regressão Linear Múltipla')
plt.xlabel('Coeficiente padronizado')
plt.tight_layout()
plt.show()

"""## 6. Modelo B — KNN de Regressão"""

# Testa valores ímpares de k até 100
bestK = 1
bestR2 = float('-inf')

tentativas_sem_melhora = 0
limite_sem_melhora = 5

for k in range(1, 100, 2):

    modelo_temp = KNeighborsRegressor(n_neighbors=k)
    modelo_temp.fit(X_treino_esc, y_treino)

    pred_temp = modelo_temp.predict(X_teste_esc)
    r2_temp = r2_score(y_teste, pred_temp)

    rmse_temp = np.sqrt(mean_squared_error(y_teste, pred_temp))

    # Verifica se o R² melhorou
    if r2_temp > bestR2:
        bestK = k
        bestR2 = r2_temp
        tentativas_sem_melhora = 0
    else:
        tentativas_sem_melhora += 1

    print(
        f'k={k:2d} | R²={r2_temp:.4f} | '
        f'RMSE={rmse_temp:,.2f} | '
        f'Sem melhora: {tentativas_sem_melhora}'
    )

    # Interrompe após 5 valores sem melhora
    if tentativas_sem_melhora >= limite_sem_melhora:
        print('\nParando: 5 valores consecutivos sem melhora.')
        break

print(f'\nMelhor k encontrado: {bestK}')
print(f'Melhor R²: {bestR2:.4f}')

modelo_knn = KNeighborsRegressor(n_neighbors=bestK)
modelo_knn.fit(X_treino_esc, y_treino)
y_pred_knn = modelo_knn.predict(X_teste_esc)

mae_knn = mean_absolute_error(y_teste, y_pred_knn)
mse_knn = mean_squared_error(y_teste, y_pred_knn)
rmse_knn = np.sqrt(mse_knn)
r2_knn = r2_score(y_teste, y_pred_knn)

print(f'MAE : {mae_knn:,.2f}')
print(f'MSE : {mse_knn:,.2f}')
print(f'RMSE: {rmse_knn:,.2f}')
print(f'R²  : {r2_knn:.4f}')

"""## 7. Comparação dos Modelos"""

resultados = pd.DataFrame({
    'Modelo': ['Regressão Linear Múltipla',  'KNN'],
    'MAE':  [mae_linear, mae_knn],
    'MSE':  [mse_linear, mse_knn],
    'RMSE': [rmse_linear, rmse_knn],
    'R²':   [r2_linear, r2_knn],
})
print('\n=== Comparação dos Modelos ===')
print(resultados.to_string(index=False))

"""### Gráfico Real vs Previsto"""

fig, eixos = plt.subplots(1, 2, figsize=(15, 4))
for eixo, (nome, pred) in zip(
    eixos,
    [('Linear', y_pred_linear),  ('KNN', y_pred_knn)]
):
    eixo.scatter(y_teste, pred, alpha=0.3, s=10)
    eixo.plot([y_teste.min(), y_teste.max()], [y_teste.min(), y_teste.max()], 'r--')
    eixo.set_xlabel('Preço real')
    eixo.set_ylabel('Preço previsto')
    eixo.set_title(f'Real vs Previsto — {nome}')
plt.tight_layout()
plt.show()